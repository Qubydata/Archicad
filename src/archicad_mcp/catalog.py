"""Searchable copy of the Tapir command reference bundled with the server.

The catalog is generated by ``scripts/sync_tapir_catalog.py`` from the Tapir
repository, so the model can discover any of the several hundred Tapir commands
and read their exact JSON schemas before calling them through
``run_tapir_command``.
"""

from __future__ import annotations

import json
import re
from functools import cache
from importlib import resources
from typing import Any


@cache
def load_catalog() -> dict[str, Any]:
    text = resources.files("archicad_mcp").joinpath("data/tapir_catalog.json").read_text(encoding="utf8")
    return json.loads(text)


@cache
def _commands_by_name() -> dict[str, dict[str, Any]]:
    return {command["name"]: command for command in load_catalog()["commands"]}


def get_command(name: str) -> dict[str, Any] | None:
    commands = _commands_by_name()
    if name in commands:
        return commands[name]
    lowered = name.lower()
    return next((c for n, c in commands.items() if n.lower() == lowered), None)


def groups() -> list[str]:
    return list(dict.fromkeys(command["group"] for command in load_catalog()["commands"]))


def search(query: str = "", group: str | None = None, limit: int = 25) -> list[dict[str, Any]]:
    """Rank commands by how many query words appear in their name and description."""
    words = [w for w in re.split(r"\W+", query.lower()) if w]
    scored = []
    for command in load_catalog()["commands"]:
        if group and command["group"].lower() != group.lower():
            continue
        name = command["name"].lower()
        text = f"{name} {command['description'].lower()}"
        if words:
            score = sum(3 if w in name else 1 for w in words if w in text)
            if score == 0:
                continue
        else:
            score = 0
        scored.append((score, command))
    scored.sort(key=lambda item: -item[0])
    return [
        {"name": c["name"], "group": c["group"], "description": c["description"]}
        for _, c in scored[:limit]
    ]


def _refs(node: Any, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/"):
            found.add(ref[2:])
        for value in node.values():
            _refs(value, found)
    elif isinstance(node, list):
        for value in node:
            _refs(value, found)


def schema_with_definitions(command: dict[str, Any]) -> dict[str, Any]:
    """Return a command's schemas plus every shared definition they reference."""
    definitions = load_catalog()["definitions"]
    pending: set[str] = set()
    _refs([command.get("inputScheme"), command.get("outputScheme")], pending)
    used: dict[str, Any] = {}
    while pending:
        name = pending.pop()
        if name in used or name not in definitions:
            continue
        used[name] = definitions[name]
        _refs(used[name], pending)
    return {
        "name": command["name"],
        "group": command["group"],
        "description": command["description"],
        "sinceTapirVersion": command.get("version"),
        "inputScheme": command.get("inputScheme"),
        "outputScheme": command.get("outputScheme"),
        "definitions": dict(sorted(used.items())),
        "note": 'A "$ref": "#/Name" points at definitions["Name"].',
    }
